const GLYPH_W = 5;
const CELL_W = 6;          // 5 colonnes + 1 d'espacement
const LINE_H = 10;         // 7 lignes + place pour les accents/cédille + 1 d'interligne

type Accent = "acute" | "grave" | "circ" | "diaer" | "cedil";
const ACCENTED: Record<string, [string, Accent]> = {
  "à": ["a", "grave"], "â": ["a", "circ"], "ä": ["a", "diaer"], "é": ["e", "acute"], "è": ["e", "grave"],
  "ê": ["e", "circ"], "ë": ["e", "diaer"], "î": ["i", "circ"], "ï": ["i", "diaer"], "ô": ["o", "circ"],
  "ö": ["o", "diaer"], "ù": ["u", "grave"], "û": ["u", "circ"], "ü": ["u", "diaer"], "ÿ": ["y", "diaer"],
  "ç": ["c", "cedil"],
  "À": ["A", "grave"], "Â": ["A", "circ"], "Ä": ["A", "diaer"], "É": ["E", "acute"], "È": ["E", "grave"],
  "Ê": ["E", "circ"], "Ë": ["E", "diaer"], "Î": ["I", "circ"], "Ï": ["I", "diaer"], "Ô": ["O", "circ"],
  "Ö": ["O", "diaer"], "Ù": ["U", "grave"], "Û": ["U", "circ"], "Ü": ["U", "diaer"], "Ç": ["C", "cedil"],
};

// Symboles 5×7 dessinés à la main (une chaîne de 7 lignes par symbole).
const SYMBOLS: Record<string, string[]> = {
  "♥": [".#.#.", "#####", "#####", "#####", ".###.", "..#..", "....."],
  "★": ["..#..", "..#..", "#####", ".###.", ".###.", "##.##", "#...#"],
  "°": [".##..", "#..#.", "#..#.", ".##..", ".....", ".....", "....."],
  "€": ["..###", ".#...", "####.", ".#...", "####.", ".#...", "..###"],
  "…": [".....", ".....", ".....", ".....", ".....", ".....", "#.#.#"],
  "«": ["..#.#", ".#.#.", "#.#..", ".#.#.", "..#.#", ".....", "....."],
  "»": ["#.#..", ".#.#.", "..#.#", ".#.#.", "#.#..", ".....", "....."],
  "☺": [".###.", "#...#", "#.#.#", "#...#", "#.#.#", "#.###", ".###."],
};

// Caractère inconnu : petit carré creux.
const FALLBACK = ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"];

export const TEXT_ALIASES: Record<string, string> = { "’": "'", "‘": "'", "“": "\"", "”": "\"", "–": "-", "—": "-", "\t": " " };

function baseColumns(ch: string): number[] | null {
  const code = ch.charCodeAt(0);
  if (ch.length === 1 && code >= 32 && code <= 126) return ASCII_COLS.slice((code - 32) * 5, (code - 32) * 5 + 5);
  return null;
}

function fromRows(rows: string[]): [number, number][] {
  const out: [number, number][] = [];
  rows.forEach((row, y) => { for (let x = 0; x < 5; x++) if (row[x] === "#") out.push([x, y]); });
  return out;
}

/** Pixels (dx,dy) d'un caractère dans sa cellule, dy négatif = accent au-dessus d'une majuscule. */
function glyphPixels(ch: string): [number, number][] {
  const sym = SYMBOLS[ch];
  if (sym) return fromRows(sym);
  const acc = ACCENTED[ch];
  const cols = baseColumns(acc ? acc[0] : ch);
  if (!cols) return fromRows(FALLBACK);
  const out: [number, number][] = [];
  cols.forEach((col, x) => { for (let y = 0; y < 7; y++) if ((col >> y) & 1) out.push([x, y]); });
  if (acc) {
    const capital = acc[0] >= "A" && acc[0] <= "Z";
    const top = capital ? -2 : 0;           // ligne haute de l'accent
    const low = top + 1;
    switch (acc[1]) {
      case "acute": out.push([3, top], [2, low]); break;
      case "grave": out.push([1, top], [2, low]); break;
      case "circ":  out.push([2, top], [1, low], [3, low]); break;
      case "diaer": out.push([1, top], [3, top]); break;
      case "cedil": out.push([2, 7], [1, 8]); break;
    }
  }
  return out;
}

/** Largeur/hauteur en pixels d'un texte à l'échelle donnée. */
export function measureText(str: string, scale: number): { w: number; h: number } {
  const lines = str.split("\n");
  const widest = Math.max(...lines.map(l => [...l].length));
  return { w: Math.max(0, widest * CELL_W - 1) * scale, h: ((lines.length - 1) * LINE_H + 7) * scale };
}

/** Écrit un texte à partir du pixel (p.x, p.y) = coin haut-gauche de la première lettre. */
export function drawText(s: Surface, ink: Ink, p: Pt, str: string, scale: number) {
  const sc = Math.max(1, Math.min(8, Math.round(scale)));
  let cx = p.x, cy = p.y;
  for (const raw of str) {
    const ch = TEXT_ALIASES[raw] ?? raw;
    if (ch === "\n") { cx = p.x; cy += LINE_H * sc; continue; }
    if (ch !== " ") {
      for (const [gx, gy] of glyphPixels(ch)) {
        for (let dy = 0; dy < sc; dy++) for (let dx = 0; dx < sc; dx++) plot(s, ink, cx + gx * sc + dx, cy + gy * sc + dy);
      }
    }
    cx += CELL_W * sc;
  }
}

