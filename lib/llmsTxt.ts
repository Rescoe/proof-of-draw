// lib/llmsTxt.ts — contenu de /llms.txt, construit depuis lib/projectStatus.ts (source de vérité). Pur : aucune requête, aucun Redis.
// /llms.txt est une CONVENTION proposée (pas un standard obligatoire) : sa présence ne garantit le comportement d'aucun moteur ni d'aucune IA.
import {
  DESCRIPTION, HARDWARE_PENDING, HARDWARE_VALIDATED, LICENCE, LIMITS, PROOF_BLOCKS, REPOSITORY_URL, SITE_URL, TRUST_MODEL, VERIFIED_AT, VERIFIED_COMMIT, VOTE, proofBlockLine,
} from "./projectStatus";

export function buildLlmsTxt(): string {
  const lines: string[] = [
    "# Proof-of-Draw",
    "",
    `> ${DESCRIPTION}`,
    "",
    `État vérifié le ${VERIFIED_AT} (code de production \`main\` à ${VERIFIED_COMMIT}). Ce fichier est une convention de lisibilité, pas un standard obligatoire ; en cas de doute, le code et les documents datés du dépôt priment.`,
    "",
    "## Vote v2",
    "",
    `- ${VOTE.summary}`,
    `- Quorum : ${VOTE.quorum}`,
    `- ${VOTE.nonVoting}`,
    `- ${VOTE.ack}`,
    `- ${VOTE.animations}`,
    "",
    "## Blocs réels minés avec des votes v2 signés",
    "",
    ...PROOF_BLOCKS.map((b) => `- ${proofBlockLine(b)}`),
    "",
    "## Matériel",
    "",
    "Validé sur la carte réelle (vote v2 observé) :",
    ...HARDWARE_VALIDATED.map((h) => `- ${h}`),
    "",
    "Qualification matérielle restante (code compilé, vote jamais observé sur la carte ; ce n'est pas une absence de consensus) :",
    ...HARDWARE_PENDING.map((h) => `- ${h}`),
    "",
    "## Modèle de confiance",
    "",
    TRUST_MODEL,
    "",
    "Distinctions à respecter :",
    "- chaîne interne liée par hashes ≠ blockchain publique autonome ou décentralisée (elle n'existe pas) ;",
    "- signature Ed25519 réelle, vérifiée par le serveur ≠ attestation matérielle forte (aucun secure element, clés en EEPROM ou flash) ;",
    "- ACK du firmware ≠ preuve optique indépendante des pixels.",
    "",
    "## Limites",
    "",
    ...LIMITS.map((l) => `- ${l}`),
    "",
    "## Licence et droits",
    "",
    `- Code : ${LICENCE.code}`,
    `- Œuvres : ${LICENCE.works}`,
    "",
    "## Liens canoniques",
    "",
    `- [Dépôt, README et documentation](${REPOSITORY_URL})`,
    `- [Apprendre : fonctionnement, installation, feuille de route](${SITE_URL}/learn)`,
    `- [Réseau en direct](${SITE_URL}/network)`,
    `- [Galerie des œuvres](${SITE_URL}/gallery)`,
    `- [Artistes](${SITE_URL}/artists)`,
    `- [Synthèse du vote réel](${REPOSITORY_URL}/blob/main/docs/SYNTHESE_VOTE_REEL_ET_PRODUCTION_DIRECTE_2026_10_14.md)`,
    `- [État public et sources IA](${REPOSITORY_URL}/blob/main/docs/ETAT_PUBLIC_ET_SOURCES_IA_2026_10_15.md)`,
    `- [Plan sitemap](${SITE_URL}/sitemap.xml)`,
    "",
  ];
  return lines.join("\n");
}
